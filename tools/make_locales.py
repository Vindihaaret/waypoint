"""Lager waypoint/locales/*.py fra tools/translations.py og sjekker at ingenting mangler."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT))
from translations import T  # noqa: E402
from extract_strings import strings  # noqa: E402

import os  # noqa: E402
os.chdir(ROOT)
missing = [s for s in strings() if s not in T]
unused = [k for k in T if k not in strings()]
problems = []
for nb, row in T.items():
    for tr in row:
        if nb.count("{}") != tr.count("{}"):
            problems.append(f"plassholdere: {nb!r} → {tr!r}")
names = ["en", "de", "es", "fr"]
tables = {n: {} for n in names}
for nb, row in T.items():
    en = row[0]
    tables["en"][nb] = en
    for n, tr in zip(names[1:], row[1:]):
        if en in tables[n] and tables[n][en] != tr:
            problems.append(f"{n}: engelsk {en!r} har to oversettelser: {tables[n][en]!r} / {tr!r}")
        tables[n][en] = tr
for p in problems + [f"mangler: {m!r}" for m in missing]:
    print(p)
if unused:
    print("ubrukt:", unused)
if problems or missing:
    sys.exit(1)
out = ROOT / "waypoint/locales"
out.mkdir(exist_ok=True)
(out / "__init__.py").write_text('"""Oversettelser, laget av tools/make_locales.py. Ikke rediger for hånd."""\n')
doc = {"en": "English. Key: Norwegian source text.", "de": "Deutsch. Key: English text.",
       "es": "Español. Key: English text.", "fr": "Français. Key: English text."}
for n in names:
    lines = [f'"""{doc[n]} Generated by tools/make_locales.py from tools/translations.py."""', "T = {"]
    lines += [f"    {k!r}: {v!r}," for k, v in tables[n].items()]
    lines.append("}")
    (out / f"{n}.py").write_text("\n".join(lines) + "\n")
print(f"OK: {len(T)} tekster, {len(names)} språk")
